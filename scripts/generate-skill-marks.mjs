import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const root = new URL(
  "../apps/shadcn-registry/src/components/icons/skills/",
  import.meta.url,
);
const files = readdirSync(new URL("assets/", root))
  .filter((file) => file.endsWith(".svg"))
  .sort();
const marks = Object.fromEntries(
  files.map((file) => {
    const svg = readFileSync(new URL(`assets/${file}`, root), "utf8");
    // Only checked-in static geometry enters the inline registry. No scripts,
    // external resources, global IDs, or paint servers that collide across rows.
    if (
      /\b(?:id|href|style|class|on\w+)\s*=|url\(|<(?!\/?(?:svg|g|path|circle|ellipse|rect|polygon|polyline|line)\b)/i.test(
        svg,
      )
    ) {
      throw new Error(`Unsupported SVG content in ${file}`);
    }
    if (!svg.includes('viewBox="0 0 24 24"'))
      throw new Error(`Nonstandard canvas: ${file}`);
    return [
      file.slice(0, -4),
      svg
        .replace(/^<svg\b[^>]*>/, "")
        .replace(/<\/svg>\s*$/, "")
        .trim(),
    ];
  }),
);
const output = await format(
  `// Generated by scripts/generate-skill-marks.mjs from assets/*.svg.\n// Static local geometry only; never populate this map with remote/user SVG.\nexport const sourcedSkillMarks = ${JSON.stringify(marks)} as const;\n`,
  { parser: "typescript" },
);
const target = new URL("sourced-marks.ts", root);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output)
    throw new Error("Skill marks need regeneration");
} else {
  writeFileSync(target, output);
}
console.log(`Verified ${files.length} skill SVGs: ${fileURLToPath(target)}`);
