// The SDK's copy of which OAuth resource and scope each portal-host route
// needs, generated from ROUTES in @aomi-labs/account/policy (the client must
// not import a server package). `--check` fails when the committed copy drifts.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { PORTAL_SESSION, ROUTES, resourcesFor } from "../packages/account/src/policy";

const target = resolve(import.meta.dirname, "../packages/client/src/generated/route-scopes.ts");
const resources = resourcesFor("");

const rows = ROUTES.flatMap((route) => {
  if (!route.on || route.on === "appMcp" || route.to === "mcp") return [];
  const methods = Object.entries(route.methods).flatMap(([method, need]) => {
    const scope = typeof need === "string" ? need : need.oauthScope;
    return scope && scope !== "public" && scope !== PORTAL_SESSION ? [`${method}: ${JSON.stringify(scope)}`] : [];
  });
  if (!methods.length) return [];
  return [
    `  { path: ${route.path}, resource: ${JSON.stringify(resources[route.on])}, paid: ${Boolean(route.paid)}, methods: { ${methods.join(", ")} } },`,
  ];
});

const source = `// Generated by scripts/generate-route-scopes.ts from ROUTES in
// @aomi-labs/account/policy. Do not edit; run \`pnpm generate:route-scopes\`.

/** The OAuth resource (a path on the portal origin) and scope each route needs, first match wins. */
export const ROUTE_SCOPES: readonly {
  path: RegExp;
  resource: string;
  /** A signed payment also needs \`payments:submit\`. */
  paid: boolean;
  methods: Readonly<Partial<Record<string, string>>>;
}[] = [
${rows.join("\n")}
];
`;

if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== source) {
    console.error("packages/client/src/generated/route-scopes.ts drifted from ROUTES. Run `pnpm generate:route-scopes`.");
    process.exit(1);
  }
} else writeFileSync(target, source);
