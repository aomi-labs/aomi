import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const root = new URL(
  "../apps/shadcn-registry/src/components/icons/apps/",
  import.meta.url,
);
const files = readdirSync(new URL("assets/", root)).sort();
const rasterMarks = Object.fromEntries(
  files
    .filter((file) => file.endsWith(".png"))
    .map((file) => [
      file.slice(0, -4),
      `data:image/png;base64,${readFileSync(new URL(`assets/${file}`, root)).toString("base64")}`,
    ]),
);

const vectorFiles = [
  "coingecko.svg",
  "github.svg",
  "linear.svg",
  "notion.svg",
  "slack.svg",
];
const vectorMarks = Object.fromEntries(
  vectorFiles.map((file) => {
    const svg = readFileSync(new URL(`assets/${file}`, root), "utf8");
    if (
      /\b(?:id|href|style|class|on\w+)\s*=|url\(|<(?!\/?(?:svg|g|path|circle|ellipse|rect|polygon|polyline|line)\b)/i.test(
        svg,
      )
    ) {
      throw new Error(`Unsupported SVG content in ${file}`);
    }
    const viewBox = svg.match(/\bviewBox="([^"]+)"/)?.[1];
    if (!viewBox) throw new Error(`Missing viewBox in ${file}`);
    return [
      file.slice(0, -4),
      {
        viewBox,
        markup: svg
          .replace(/^<svg\b[^>]*>/, "")
          .replace(/<\/svg>\s*$/, "")
          .trim(),
      },
    ];
  }),
);

const cambrianSvg = readFileSync(new URL("assets/cambrian.svg", root), "utf8");
if (
  /\b(?:href|style|class|on\w+)\s*=|url\(|<(?!\/?(?:svg|g|path|circle|ellipse|rect|polygon|polyline|line)\b)/i.test(
    cambrianSvg,
  )
) {
  throw new Error("Unsupported SVG content in cambrian.svg");
}
const cambrianMarkup = cambrianSvg
  .replace(/^<svg\b[^>]*>/, "")
  .replace(/<\/svg>\s*$/, "")
  .replaceAll('fill="rgb(249,246,241)"', 'fill="none"')
  .replaceAll('fill="rgb(75,147,40)"', 'fill="currentColor"')
  .trim();
if (/rgb\(|#[0-9a-f]{3,8}/i.test(cambrianMarkup)) {
  throw new Error("Cambrian mark still contains fixed color");
}

const etherscanSvg = readFileSync(
  new URL("assets/etherscan.svg", root),
  "utf8",
);
const etherscanPaths = etherscanSvg.match(/<path\b[^>]*\/>/g) ?? [];
if (etherscanPaths.length < 3)
  throw new Error("Etherscan symbol paths missing");
const etherscanMarkup = etherscanPaths
  .slice(-2)
  .join("")
  .replace(/fill="#[0-9A-Fa-f]+"/g, 'fill="currentColor"');

const output = await format(
  `// Generated by scripts/generate-app-marks.mjs from apps/assets/*.
// Static local artwork only; never populate this map with remote/user content.
export const sourcedAppRasterMarks = ${JSON.stringify(rasterMarks)} as const;
export const sourcedAppVectorMarks = ${JSON.stringify(vectorMarks)} as const;
export const cambrianAppMarkup = ${JSON.stringify(cambrianMarkup)};
export const etherscanAppMarkup = ${JSON.stringify(etherscanMarkup)};
`,
  { parser: "typescript" },
);
const target = new URL("sourced-marks.ts", root);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) {
    throw new Error("App marks need regeneration");
  }
} else {
  writeFileSync(target, output);
}
console.log(`Verified ${files.length} app sources: ${fileURLToPath(target)}`);
